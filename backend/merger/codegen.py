"""Generate a standalone, reproducible clean.py from a merge plan.

The script only needs pandas (plus openpyxl for Excel inputs). Unit conversions
are written out as plain linear formulas with a comment saying where they came
from, so a reviewer can read exactly what happened to every column.
"""

from __future__ import annotations

import re
from datetime import datetime

from . import units
from .plan import MergePlan


def _func_name(fname: str) -> str:
    stem = re.sub(r"\.[^.]+$", "", fname)
    return "load_" + (re.sub(r"\W+", "_", stem).strip("_").lower() or "file")


def _date_expr(col_expr: str, fmt: str | None) -> str:
    if fmt is None:
        return "pd.NaT"
    if fmt == "native":
        return f"pd.to_datetime({col_expr}, errors='coerce')"
    return f"pd.to_datetime({col_expr}.astype('string').str.strip(), format={fmt!r}, errors='coerce')"


def generate_clean_script(plan: MergePlan) -> str:
    targets = plan.targets
    lines: list[str] = []
    w = lines.append

    w('"""clean.py: generated by Schemata on ' + datetime.now().strftime("%Y-%m-%d %H:%M") + ".")
    w("")
    w("Merges the raw files below into one clean table with columns:")
    for t, spec in targets.items():
        unit = f" [{spec['unit']}]" if spec.get("unit") else ""
        w(f"    {t}{unit}")
    w("")
    w("Usage:  python clean.py [DATA_DIR] [OUTPUT_CSV]")
    w('"""')
    w("")
    w("import sys")
    w("from pathlib import Path")
    w("")
    w("import pandas as pd")
    w("")
    w("DATA_DIR = Path(sys.argv[1]) if len(sys.argv) > 1 else Path(__file__).parent")
    w('OUTPUT = Path(sys.argv[2]) if len(sys.argv) > 2 else DATA_DIR / "merged.csv"')
    w("")
    w(f"COLUMNS = {['source_file', *targets]!r}")
    w("")
    w("")
    w("def read(name):")
    w("    path = DATA_DIR / name")
    w("    if path.suffix.lower() in {'.xlsx', '.xlsm', '.xls'}:")
    w("        return pd.read_excel(path)")
    w("    return pd.read_csv(path)")

    func_names = []
    for fp in plan.files:
        fn = _func_name(fp.file)
        func_names.append(fn)
        w("")
        w("")
        w(f"def {fn}():")
        w(f"    src = read({fp.file!r})")
        w("    out = pd.DataFrame(index=src.index)")
        w(f"    out['source_file'] = {fp.file!r}")
        for target, spec in targets.items():
            m = fp.mapping_for(target)
            if m is None:
                w(f"    out[{target!r}] = pd.NA  # no matching column in this file")
                continue
            col = f"src[{m.source!r}]"
            if spec["kind"] == "quantity":
                from_unit = m.unit or spec["unit"]
                a, b = units.linear_coefficients(from_unit, spec["unit"])
                how = m.unit_source or "default"
                w(f"    # {m.source!r}: {from_unit} -> {spec['unit']} ({how})")
                if m.unit_source == "inferred" and m.unit_note:
                    w(f"    #   {m.unit_note}")
                expr = f"pd.to_numeric({col}, errors='coerce')"
                if abs(a - 1.0) > 1e-12:
                    expr += f" * {a!r}"
                if abs(b) > 1e-12:
                    expr += f" - {-b!r}" if b < 0 else f" + {b!r}"
                w(f"    out[{target!r}] = {expr}")
            elif spec["kind"] == "datetime":
                if m.date_note:
                    w(f"    # {m.date_note}")
                w(f"    out[{target!r}] = {_date_expr(col, m.date_format)}")
            else:
                w(f"    out[{target!r}] = {col}.astype('string').str.strip()")
        w("    return out[COLUMNS]")

    w("")
    w("")
    w("def check(df):")
    w('    """Validation checks. Errors stop the script; warnings are printed."""')
    w("    errors, warnings = [], []")
    for target, spec in targets.items():
        if spec["kind"] == "id":
            w(f"    if df[{target!r}].isna().any():")
            w(f"        errors.append('missing {target} in ' + str(df[{target!r}].isna().sum()) + ' row(s)')")
            w(f"    if df[{target!r}].dropna().duplicated().any():")
            w(f"        warnings.append('duplicate {target} values')")
        elif spec["kind"] == "datetime":
            w(f"    if df[{target!r}].isna().any():")
            w(f"        warnings.append(str(df[{target!r}].isna().sum()) + ' unparsed {target} value(s)')")
        elif spec["kind"] == "quantity" and "valid_range" in spec:
            lo, hi = spec["valid_range"]
            w(f"    bad = df[(df[{target!r}] < {lo!r}) | (df[{target!r}] > {hi!r})]")
            w("    if len(bad):")
            w(f"        errors.append(str(len(bad)) + ' {target} value(s) outside {lo}..{hi} {spec['unit']}')")
    w("    for msg in warnings:")
    w("        print('WARNING:', msg)")
    w("    if errors:")
    w("        raise SystemExit('Validation failed:\\n  ' + '\\n  '.join(errors))")
    w("")
    w("")
    w("def main():")
    w("    df = pd.concat([")
    for fn in func_names:
        w(f"        {fn}(),")
    w("    ], ignore_index=True)")
    w("    check(df)")
    w("    df.to_csv(OUTPUT, index=False)")
    w("    print(f'Wrote {len(df)} rows to {OUTPUT}')")
    w("")
    w("")
    w('if __name__ == "__main__":')
    w("    main()")
    w("")
    return "\n".join(lines)
